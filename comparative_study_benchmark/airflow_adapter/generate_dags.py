"""
Synthetic DAG generator for the Airflow scheduler-bottleneck benchmark (paper Section 4.3).

Generates N Airflow DAG definition files, each with F dynamically-mapped sibling
tasks, and a task-duration mixture M controlling the short/long split described
in Section 4.1 of the paper. DAGs use a no-op / sleep-based task body so that
measured latency reflects scheduler and executor overhead rather than
task-internal computation time (paper Section 4.3).

Usage:
    python generate_dags.py --n 1000 --f 500 --m 0.9 --out ./generated_dags \
        --shard-id 0 --shard-count 1 --prefix bench

Each generated file defines exactly one DAG. Files are named
    {prefix}_{dag_index:06d}.py
DAG identity (and therefore its file name) does NOT depend on shard_id/
shard_count -- only which files get WRITTEN by a given invocation does.
Running this script once per shard_id in {0..shard_count-1} against the same
--out directory (or per-shard directories) yields a complete, non-overlapping
partition of all N DAGs, with each DAG's shard membership determined by
hash(DAG_ID) % N_s (paper Section 5.1), independent of generation order.
"""
import argparse
import os
import textwrap
import hashlib


DAG_TEMPLATE = '''"""
Auto-generated benchmark DAG. DO NOT EDIT BY HAND.
Generated by dag_generator/generate_dags.py -- see paper Section 4.3.

Params: N={n} F={fan_out} short_ratio={short_ratio} dag_index={dag_index}
"""
from datetime import datetime, timedelta
import time
import random

from airflow.decorators import dag, task
from airflow.operators.python import get_current_context


DAG_ID = "{dag_id}"
FAN_OUT = {fan_out}
SHORT_RATIO = {short_ratio}          # fraction of mapped tasks that are "short"
SHORT_DURATION_SEC = {short_dur}     # sub-second control-flow-style task
LONG_DURATION_SEC = {long_dur}       # multi-minute compute-style task


def _duration_for_index(i: int) -> float:
    """Deterministic short/long assignment so repeated runs are comparable."""
    # Stable pseudo-random split seeded by (dag + mapped index), not wall clock,
    # so the same (N, F, M) configuration produces the same duration mixture
    # across repeated runs (paper Section 4.2 -- min. 5 repeats per config).
    rnd = random.Random(f"{{DAG_ID}}-{{i}}")
    return SHORT_DURATION_SEC if rnd.random() < SHORT_RATIO else LONG_DURATION_SEC


@dag(
    dag_id=DAG_ID,
    schedule=None,                     # triggered externally by the harness
    start_date=datetime(2024, 1, 1),
    catchup=False,
    max_active_runs=1,
    tags=["benchmark", "worksatsc-airflow-scheduler-study"],
)
def benchmark_dag():

    @task
    def make_indices():
        # Fan-out driver: produces FAN_OUT indices for dynamic task mapping
        # (paper Section 4.3 -- "Airflow's dynamic task mapping API").
        return list(range(FAN_OUT))

    @task
    def sibling_task(i: int):
        ctx = get_current_context()
        ti = ctx["ti"]
        t0 = time.monotonic()
        duration = _duration_for_index(i)
        time.sleep(duration)
        elapsed = time.monotonic() - t0
        # Emit a metric-friendly log line the metrics collector can also
        # scrape as a fallback if StatsD/Prometheus sampling misses this task.
        print(f"BENCH_TASK_DONE dag={{DAG_ID}} index={{i}} "
              f"target_duration={{duration:.3f}} elapsed={{elapsed:.3f}} "
              f"try_number={{ti.try_number}}")

    sibling_task.expand(i=make_indices())


benchmark_dag()
'''


def stable_dag_id(prefix: str, dag_index: int) -> str:
    # Deliberately independent of which shard invocation is generating it --
    # shard assignment must be a pure function of a DAG's identity (via
    # shard_of() below), not of who happened to generate the file, or the
    # hash(DAG_ID) % N_s partitioning in Section 5.1 would be meaningless.
    return f"{prefix}_{dag_index:06d}"


def shard_of(dag_id: str, shard_count: int) -> int:
    """Matches the hash(DAG_ID) % N_s partitioning used in paper Section 5.1."""
    h = int(hashlib.sha256(dag_id.encode("utf-8")).hexdigest(), 16)
    return h % shard_count


def generate(n, fan_out, short_ratio, short_dur, long_dur, out_dir,
             prefix, shard_id, shard_count):
    os.makedirs(out_dir, exist_ok=True)
    written = 0
    for dag_index in range(n):
        dag_id = stable_dag_id(prefix, dag_index)

        # If sharding is requested (shard_count > 1), only materialize DAGs
        # whose stable hash routes to this shard -- mirrors the DAG-sharding
        # mitigation's static partitioning described in Section 5.1. Because
        # dag_id no longer encodes shard_id, the same dag_index always hashes
        # to the same shard regardless of which invocation generates it, so
        # running this once per shard_id in {0..shard_count-1} produces a
        # complete, non-overlapping partition of all N DAGs.
        if shard_count > 1 and shard_of(dag_id, shard_count) != shard_id:
            continue

        content = DAG_TEMPLATE.format(
            n=n,
            fan_out=fan_out,
            short_ratio=short_ratio,
            short_dur=short_dur,
            long_dur=long_dur,
            dag_index=dag_index,
            dag_id=dag_id,
        )
        path = os.path.join(out_dir, f"{dag_id}.py")
        with open(path, "w") as f:
            f.write(content)
        written += 1
    return written


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n", type=int, required=True, help="DAG count (N)")
    ap.add_argument("--f", type=int, required=True, dest="fan_out",
                     help="Fan-out per DAG (F): number of dynamically-mapped sibling tasks")
    ap.add_argument("--m", type=float, required=True, dest="short_ratio",
                     help="Duration mixture (M): fraction of mapped tasks that are 'short' "
                          "(e.g. 0.9 for the 90/10 short/long point in Table 1)")
    ap.add_argument("--short-dur", type=float, default=0.5,
                     help="Duration in seconds for 'short' control-flow-style tasks")
    ap.add_argument("--long-dur", type=float, default=180.0,
                     help="Duration in seconds for 'long' compute-style tasks")
    ap.add_argument("--out", required=True, help="Output directory for generated DAG files")
    ap.add_argument("--prefix", default="bench", help="DAG id prefix")
    ap.add_argument("--shard-id", type=int, default=0,
                     help="This generator invocation's shard id (Section 5.1)")
    ap.add_argument("--shard-count", type=int, default=1,
                     help="Total number of shards, N_s (Section 5.1). 1 = unsharded baseline.")
    args = ap.parse_args()

    if not (0.0 <= args.short_ratio <= 1.0):
        ap.error("--m must be between 0.0 and 1.0")

    written = generate(
        n=args.n, fan_out=args.fan_out, short_ratio=args.short_ratio,
        short_dur=args.short_dur, long_dur=args.long_dur,
        out_dir=args.out, prefix=args.prefix,
        shard_id=args.shard_id, shard_count=args.shard_count,
    )
    print(f"Wrote {written} DAG file(s) to {args.out} "
          f"(N={args.n}, F={args.fan_out}, M={args.short_ratio}, "
          f"shard {args.shard_id}/{args.shard_count})")


if __name__ == "__main__":
    main()
