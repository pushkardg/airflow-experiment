"""
Kubeflow Pipelines generator for the comparative-study benchmark (paper
Section 4.1, "Kubeflow adapter").

Generates N KFP v2 pipeline Python modules, each expressing F sibling tasks
via dsl.ParallelFor, with a short/long duration mixture M -- the same
(N, F, M) contract as the Airflow and Argo adapters.

KFP v2's dsl.ParallelFor iterates over a plain list cleanly, but iterating a
list of *structured* items (e.g. {"index":.., "duration":..}) and referencing
per-item fields inside the loop body requires typed NamedTuple/artifact
plumbing that adds real compilation risk. To keep every generated pipeline
reliably compilable (paper Section 4.5's "adapter, not reimplementation"
principle), we instead split the F sibling tasks into two static groups by
the same deterministic short/long assignment the Airflow and Argo adapters
use, and run one ParallelFor per group with a fixed duration constant --
same duration-mixture semantics (a fraction M is short, 1-M is long), just
grouped rather than per-item-typed.

Usage:
    python generate_pipeline.py --n 100 --f 50 --m 0.9 --out ./generated_pipelines

Each generated .py file is compiled in-process via the KFP SDK's own
compiler (kfp.compiler.Compiler) to a pipeline_spec YAML file -- this is a
real correctness check (the KFP SDK either compiles the pipeline or raises),
not merely a syntax check.
"""
import argparse
import os
import random

PIPELINE_TEMPLATE_HEADER = '''"""
Auto-generated benchmark pipeline. DO NOT EDIT BY HAND.
Generated by kubeflow_adapter/generate_pipeline.py -- see paper Section 4.1.

Params: N={n} F={fan_out} short_ratio={short_ratio} pipeline_index={pipeline_index}
"""
from kfp import dsl


SHORT_INDICES = {short_indices}
LONG_INDICES = {long_indices}
SHORT_DURATION_SEC = {short_dur}
LONG_DURATION_SEC = {long_dur}


@dsl.component(base_image="python:3.11-slim")
def sibling_task(i: int, duration: float):
    import time
    t0 = time.monotonic()
    time.sleep(duration)
    elapsed = time.monotonic() - t0
    print(f"BENCH_TASK_DONE index={{i}} target_duration={{duration:.3f}} elapsed={{elapsed:.3f}}")


@dsl.pipeline(name="{pipeline_name}")
def fanout_demo_pipeline():
'''

# KFP's dsl.ParallelFor rejects an empty item list outright (raises
# ValueError), which a real compile-time check caught during testing: with
# small F, the deterministic short/long split (mirroring the Airflow/Argo
# adapters) can legitimately produce an empty group. Each ParallelFor block
# is therefore only emitted when its group is non-empty; if fan_out ends up
# 0 for the whole pipeline (F=0), a single no-op pass statement is emitted
# so the pipeline body is never syntactically empty.
PARALLEL_FOR_BLOCK = '''    with dsl.ParallelFor(items={indices}) as i:
        sibling_task(i=i, duration={duration_const})
'''


def stable_pipeline_name(prefix: str, index: int) -> str:
    return f"{prefix}-{index:06d}"


def split_indices(pipeline_name: str, fan_out: int, short_ratio: float):
    """Deterministic short/long split, mirroring the Airflow/Argo adapters'
    per-index duration assignment (paper Section 4.1's cross-system
    equivalence requirement), grouped rather than per-item for KFP
    compilation simplicity (see module docstring)."""
    short, long = [], []
    for i in range(fan_out):
        rnd = random.Random(f"{pipeline_name}-{i}")
        (short if rnd.random() < short_ratio else long).append(i)
    return short, long


def write_pipeline_source(n, fan_out, short_ratio, short_dur, long_dur, out_dir, prefix):
    if fan_out < 1:
        # Discovered via real KFP-compiler testing (not assumed): a pipeline
        # with zero tasks raises "ValueError: Task is missing from pipeline."
        # at compile time. This is a genuine constraint of KFP v2's graph
        # model, absent from the Airflow (.expand() over an empty list is
        # legal) and Argo (an empty withItems list is legal) adapters --
        # worth noting directly in paper Section 5.4 as a discovered
        # cross-system difference. F=0 is outside the paper's tested range
        # (Table 1: F in {1, 50, 500}) so we reject it here rather than
        # work around it with a fabricated no-op task.
        raise ValueError(
            "fan_out (F) must be >= 1 for the Kubeflow adapter: KFP v2 "
            "raises 'Task is missing from pipeline' for a zero-task "
            "pipeline. F=0 is outside this paper's tested range (Table 1) "
            "for this reason -- see module docstring."
        )
    os.makedirs(out_dir, exist_ok=True)
    written_paths = []
    for index in range(n):
        name = stable_pipeline_name(prefix, index)
        short_idx, long_idx = split_indices(name, fan_out, short_ratio)

        header = PIPELINE_TEMPLATE_HEADER.format(
            n=n, fan_out=fan_out, short_ratio=short_ratio, pipeline_index=index,
            short_indices=short_idx, long_indices=long_idx,
            short_dur=short_dur, long_dur=long_dur,
            pipeline_name=name.replace("_", "-"),
        )

        body_blocks = []
        if short_idx:
            body_blocks.append(PARALLEL_FOR_BLOCK.format(
                indices="SHORT_INDICES", duration_const="SHORT_DURATION_SEC"))
        if long_idx:
            body_blocks.append(PARALLEL_FOR_BLOCK.format(
                indices="LONG_INDICES", duration_const="LONG_DURATION_SEC"))
        # fan_out >= 1 is now guaranteed, so at least one of short_idx/long_idx
        # is guaranteed non-empty and body_blocks is never empty here.

        content = header + "".join(body_blocks)
        path = os.path.join(out_dir, f"{name}.py")
        with open(path, "w") as f:
            f.write(content)
        written_paths.append(path)
    return written_paths


def compile_pipeline(py_path: str, ir_out_path: str) -> None:
    """Dynamically imports a generated pipeline module and compiles it via
    the real KFP SDK compiler -- this either succeeds (valid pipeline IR
    written to ir_out_path) or raises, so it is a genuine correctness check
    rather than a syntax-only check."""
    import importlib.util
    from kfp import compiler

    spec = importlib.util.spec_from_file_location("generated_pipeline_module", py_path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)

    compiler.Compiler().compile(
        pipeline_func=mod.fanout_demo_pipeline,
        package_path=ir_out_path,
    )


def generate(n, fan_out, short_ratio, short_dur, long_dur, out_dir, prefix,
             also_compile=False, ir_out_dir=None):
    paths = write_pipeline_source(n, fan_out, short_ratio, short_dur, long_dur, out_dir, prefix)
    compiled = 0
    if also_compile:
        os.makedirs(ir_out_dir, exist_ok=True)
        for p in paths:
            name = os.path.splitext(os.path.basename(p))[0]
            ir_path = os.path.join(ir_out_dir, f"{name}.yaml")
            compile_pipeline(p, ir_path)
            compiled += 1
    return paths, compiled


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n", type=int, required=True)
    ap.add_argument("--f", type=int, required=True, dest="fan_out")
    ap.add_argument("--m", type=float, required=True, dest="short_ratio")
    ap.add_argument("--short-dur", type=float, default=0.5)
    ap.add_argument("--long-dur", type=float, default=180.0)
    ap.add_argument("--out", required=True)
    ap.add_argument("--prefix", default="bench")
    ap.add_argument("--compile", action="store_true",
                     help="Also compile each generated pipeline to KFP IR via the real KFP SDK compiler")
    ap.add_argument("--ir-out", default=None,
                     help="Output directory for compiled IR YAML (required if --compile)")
    args = ap.parse_args(argv)

    if not (0.0 <= args.short_ratio <= 1.0):
        ap.error("--m must be between 0.0 and 1.0")
    if args.fan_out < 1:
        ap.error("--f (fan_out) must be >= 1 for the Kubeflow adapter -- "
                  "see module docstring / write_pipeline_source() for why")
    if args.compile and not args.ir_out:
        ap.error("--ir-out is required when --compile is set")

    paths, compiled = generate(
        n=args.n, fan_out=args.fan_out, short_ratio=args.short_ratio,
        short_dur=args.short_dur, long_dur=args.long_dur,
        out_dir=args.out, prefix=args.prefix,
        also_compile=args.compile, ir_out_dir=args.ir_out,
    )
    msg = (f"Wrote {len(paths)} KFP pipeline source file(s) to {args.out} "
           f"(N={args.n}, F={args.fan_out}, M={args.short_ratio})")
    if args.compile:
        msg += f"; compiled {compiled} to IR YAML in {args.ir_out}"
    print(msg)


if __name__ == "__main__":
    main()
